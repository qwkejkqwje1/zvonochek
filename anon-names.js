// FNV-1a 32 бита — стабильный дешёвый хэш строки (не криптография:
// имя — только подпись для глаз, из него ничего не выводится).
function fnv(str) {
  let h = 0x811c9dc5;
  const s = String(str || '');
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

function compose(a, n) {
  const [word, g] = NOUN[n % NOUN.length];
  return ADJ[a % ADJ.length][g] + ' ' + word;
}

export function anonName(seed) {
  const h = fnv('zv-anon|' + seed);
  return compose(h & 0xffff, h >>> 16);
}

export function randomAnonName() {
  const r = crypto.getRandomValues(new Uint32Array(2));
  return compose(r[0], r[1]);
}

export const ANON_COUNT = ADJ.length * NOUN.length;
